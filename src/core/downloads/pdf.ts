// Minimal PDF writer, port of the prototype `makePdf` (one page per comic page, Helvetica text).
export function makePdf(title: string, pages: number): string {
  const esc2 = (x: string) => x.replace(/[()\\]/g, '');
  const objs: string[] = [];
  const add = (x: string) => (objs.push(x), objs.length);
  add('<< /Type /Catalog /Pages 2 0 R >>');
  add('');
  const font = add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  const kids: string[] = [];
  for (let i = 1; i <= pages; i++) {
    const txt = `BT /F1 24 Tf 60 740 Td (${esc2(title)}) Tj ET BT /F1 14 Tf 60 700 Td (Page ${i} of ${pages}) Tj ET BT /F1 11 Tf 60 670 Td (Generated by Cinetor) Tj ET`;
    const c = add(`<< /Length ${txt.length} >>\nstream\n${txt}\nendstream`);
    const pg = add(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents ${c} 0 R /Resources << /Font << /F1 ${font} 0 R >> >> >>`);
    kids.push(pg + ' 0 R');
  }
  objs[1] = `<< /Type /Pages /Kids [${kids.join(' ')}] /Count ${pages} >>`;
  let out = '%PDF-1.4\n';
  const off: number[] = [];
  objs.forEach((o, i) => {
    off.push(out.length);
    out += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const x = out.length;
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + off.map((o) => String(o).padStart(10, '0') + ' 00000 n \n').join('') + `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${x}\n%%EOF`;
  return out;
}
